    # Part 17. Statistics
    # ==========================================================================

    @property
    def trace_count(self) -> int:
        return self._statistics.trace_count


    @property
    def span_count(self) -> int:
        return self._statistics.span_count


    @property
    def active_span_count(self) -> int:
        manager = self._manager

        value = getattr(
            manager,
            "span_depth",
            None,
        )

        if value is not None:
            return int(value)

        return 1 if self.current_span is not None else 0


    @property
    def exported_count(self) -> int:
        return self._statistics.exported_count


    @property
    def error_count(self) -> int:
        return self._statistics.error_count



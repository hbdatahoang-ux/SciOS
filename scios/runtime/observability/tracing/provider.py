class ProviderType(Enum):
    """
    Type of tracing provider.
    """

    DEFAULT = auto()
    RUNTIME = auto()
    CUSTOM = auto()


class ProviderState(Enum):
    """
    Runtime state of a TraceProvider.
    """

    CREATED = auto()
    STARTING = auto()
    RUNNING = auto()
    STOPPING = auto()
    STOPPED = auto()
    ERROR = auto()
    CLOSED = auto()


class ProviderCapability(Enum):
    """
    Capabilities exposed by a TraceProvider.
    """

    TRACE = auto()
    SPAN = auto()
    CONTEXT = auto()
    SAMPLING = auto()
    PROCESSING = auto()
    EXPORTING = auto()
    SNAPSHOT = auto()
    VALIDATION = auto()


